"""Regenerates the sample ZIP project and sample Excel reports.
Run from the project root:  python scripts/make_samples.py

The Excel values are ILLUSTRATIVE sample data (not produced by any real tool)."""
import zipfile
from pathlib import Path

from openpyxl import Workbook

ROOT = Path(__file__).resolve().parent.parent

# --- ZIP of the sample project ------------------------------------------------
project = ROOT / "sample_projects" / "embedded_demo"
with zipfile.ZipFile(ROOT / "sample_projects" / "embedded_demo.zip", "w", zipfile.ZIP_DEFLATED) as zf:
    for path in sorted(project.rglob("*")):
        if path.is_file():
            zf.write(path, path.relative_to(project).as_posix())

# --- Excel reports --------------------------------------------------------------
out = ROOT / "sample_reports"
out.mkdir(exist_ok=True)

wb = Workbook()
ws = wb.active
ws.title = "Complexity Report"
ws.append(["Complexity report (illustrative sample data)"])
ws.append(["Generated by: ExampleTool 1.0"])
ws.append([])
ws.append(["Module", "Routine", "V(G)", "Start", "End", "Max V(G)", "Parameters"])
rows = [
    ("src/uart_driver.c", "uart_init", 2, 11, 16, 10, 1),
    ("src/uart_driver.c", "uart_send", 8, 18, 33, 10, 3),
    ("src/uart_driver.c", "uart_parse_frame", 14, 35, 62, 10, 2),
    ("src/filter.cpp", "MovingAverage::MovingAverage", 2, 6, 6, 10, 1),
    ("src/filter.cpp", "MovingAverage::push", 4, 8, 19, 10, 1),
    ("src/filter.cpp", "clamp", 3, 26, 30, 10, 3),
    ("src/legacy_motor.c", "motor_step", 21, 40, 180, 10, 4),
    ("src/legacy_motor.c", "motor_calibrate", 10, 190, 240, 10, 2),
    ("src/legacy_motor.c", "motor_stop", 1, 250, 255, 10, 0),
    ("src/legacy_motor.c", "motor_fault_handler", 12, 260, 330, 10, 1),
]
for r in rows:
    ws.append(list(r))
notes = wb.create_sheet("Notes")
notes.append(["This worksheet only contains notes and no complexity data."])
wb.save(out / "sample_complexity_report.xlsx")

wb = Workbook()
ws = wb.active
ws.title = "Export"
ws.append(["Col A", "Col B", "Col C", "Col D"])
for r in [("src/a.c", "alpha", 3, 12), ("src/a.c", "beta", 17, 40), ("src/b.c", "gamma", 9, 7)]:
    ws.append(list(r))
wb.save(out / "unmapped_headers_report.xlsx")

wb = Workbook()
ws = wb.active
ws.title = "Metrics"
ws.append(["File", "Function", "Lines of Code"])
for r in [("src/a.c", "alpha", 12), ("src/a.c", "beta", 40)]:
    ws.append(list(r))
wb.save(out / "no_complexity_column_report.xlsx")
print("Samples written.")
