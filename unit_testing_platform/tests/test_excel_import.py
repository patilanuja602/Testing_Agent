import pytest

from config import Limits, MB
from services.excel_importer import (
    ColumnMapping, ExcelImportError, apply_header, detect_header_row, import_records, read_raw_sheet,
    read_sheet_names, suggest_mapping, suggest_report_threshold, validate_excel_upload, validate_mapping,
)
from models.analysis_result import AnalysisStatus
from tests.helpers import SMALL_LIMITS, make_xlsx

REPORT = [
    ["Complexity report generated by SomeTool", None, None, None],
    [None, None, None, None],
    ["Module", "Routine", "V(G)", "Start", "Max V(G)"],
    ["src/a.c", "alpha", 4, 10, 10],
    ["src/a.c", "beta", 12, 30, 10],
    ["src/b.cpp", "gamma", 10.0, 5, 10],
]


def load(data, sheet=None):
    sheet = sheet or read_sheet_names(data)[0]
    raw = read_raw_sheet(data, sheet)
    det = detect_header_row(raw)
    return apply_header(raw, det.row_index), det


def test_header_row_detected_below_title_rows():
    df, det = load(make_xlsx({"Report": REPORT}))
    assert det.confident and list(df.columns)[:3] == ["Module", "Routine", "V(G)"]
    assert len(df) == 3


def test_automatic_mapping_of_unusual_names():
    df, _ = load(make_xlsx({"Report": REPORT}))
    m = suggest_mapping(df)
    assert (m.file, m.function, m.complexity, m.start_line, m.threshold) == ("Module", "Routine", "V(G)", "Start", "Max V(G)")
    assert validate_mapping(df, m).ok


def test_import_normalises_records_and_preserves_original_data():
    df, _ = load(make_xlsx({"Report": REPORT}))
    out = import_records(df, suggest_mapping(df), sheet="Report", source_name="r.xlsx")
    assert [(r.function, r.ccn, r.start_line, r.file) for r in out.results] == [
        ("alpha", 4, 10, "src/a.c"), ("beta", 12, 30, "src/a.c"), ("gamma", 10, 5, "src/b.cpp")]
    assert out.results[1].original_data["V(G)"] == 12
    assert out.results[1].imported_threshold == 10.0
    assert out.results[2].language == "C++" and out.results[2].origin == "excel"
    assert all(r.end_line is None and r.nloc is None for r in out.results)       # not fabricated
    assert suggest_report_threshold(df, suggest_mapping(df)) == 10


def test_manual_mapping_when_headers_are_unrecognisable():
    rows = [["Col A", "Col B", "Col C"], ["x.c", "f1", 3], ["x.c", "f2", 20]]
    df, det = load(make_xlsx({"S": rows}))
    assert not det.confident
    auto = suggest_mapping(df)
    assert auto.complexity is None and not validate_mapping(df, auto).ok
    manual = ColumnMapping(file="Col A", function="Col B", complexity="Col C")
    assert validate_mapping(df, manual).ok
    out = import_records(df, manual, sheet="S", source_name="r.xlsx")
    assert [r.ccn for r in out.results] == [3, 20]


def test_missing_complexity_column_gives_clear_explanation():
    df, _ = load(make_xlsx({"S": [["File", "Function", "Lines"], ["a.c", "f", 10]]}))
    check = validate_mapping(df, suggest_mapping(df))
    assert not check.ok and "original source code" in check.errors[0]
    with pytest.raises(ExcelImportError):
        import_records(df, suggest_mapping(df), sheet="S", source_name="r.xlsx")


def test_threshold_column_is_not_mistaken_for_complexity():
    df, _ = load(make_xlsx({"S": [["File", "Function", "Complexity Threshold", "Cyclomatic Complexity"], ["a.c", "f", 10, 3]]}))
    m = suggest_mapping(df)
    assert m.complexity == "Cyclomatic Complexity" and m.threshold == "Complexity Threshold"


def test_bad_values_become_visible_warnings_not_successes():
    rows = [["File", "Function", "CCN"], ["a.c", "ok", 5], ["a.c", "text", "n/a"], ["a.c", "frac", 2.5],
            ["a.c", None, 7], ["a.c", "blank", None], ["a.c", "neg", -3],
            [None, "Total", 99]]
    df, _ = load(make_xlsx({"S": rows}))
    out = import_records(df, suggest_mapping(df), sheet="S", source_name="r.xlsx")
    by_name = {r.function: r for r in out.results}
    assert by_name["ok"].analysis_status is AnalysisStatus.SUCCESS
    for name in ("text", "frac", "blank", "neg"):
        assert by_name[name].ccn is None and by_name[name].analysis_status is AnalysisStatus.WARNING and by_name[name].warnings
    assert by_name["<unnamed>"].ccn == 7 and "Function name is missing" in by_name["<unnamed>"].warnings
    assert any("summary" in reason for _, reason in out.skipped_rows)               # reported, not silent
    assert "Total" not in by_name


def test_duplicates_are_flagged_not_removed():
    rows = [["File", "Function", "CCN"], ["a.c", "f", 3], ["a.c", "f", 3], ["a.c", "g", 1]]
    df, _ = load(make_xlsx({"S": rows}))
    out = import_records(df, suggest_mapping(df), sheet="S", source_name="r.xlsx")
    assert len(out.results) == 3
    assert sum(1 for r in out.results if any("Duplicate" in w for w in r.warnings)) == 2
    assert any("Duplicate" in w for w in out.warnings)


def test_multiple_sheets_listed():
    data = make_xlsx({"Notes": [["hello"]], "Report": REPORT})
    assert read_sheet_names(data) == ["Notes", "Report"]


def test_invalid_inputs_rejected():
    ok = make_xlsx({"S": REPORT})
    with pytest.raises(ExcelImportError, match="xls"):
        validate_excel_upload("old.xls", ok, SMALL_LIMITS)
    with pytest.raises(ExcelImportError):
        validate_excel_upload("r.xlsx", b"", SMALL_LIMITS)
    with pytest.raises(ExcelImportError):
        validate_excel_upload("r.xlsx", b"not an excel file", SMALL_LIMITS)
    with pytest.raises(ExcelImportError):
        validate_excel_upload("r.csv", ok, SMALL_LIMITS)
    with pytest.raises(ExcelImportError, match="size limit"):
        validate_excel_upload("r.xlsx", ok, Limits(1, 1, 1, 1, 1, 10))
    with pytest.raises(ExcelImportError):
        read_sheet_names(b"PK\x03\x04garbage-not-a-workbook")


def test_empty_sheet_rejected():
    data = make_xlsx({"Empty": [[None, None]], "Real": REPORT})
    with pytest.raises(ExcelImportError, match="empty"):
        read_raw_sheet(data, "Empty")


def test_repository_sample_reports_import():
    from pathlib import Path
    sample = Path(__file__).parent.parent / "sample_reports" / "sample_complexity_report.xlsx"
    if not sample.exists():
        pytest.skip("sample report not generated")
    data = sample.read_bytes()
    validate_excel_upload(sample.name, data, SMALL_LIMITS)
    df, det = load(data, "Complexity Report")
    out = import_records(df, suggest_mapping(df), sheet="Complexity Report", source_name=sample.name)
    assert len(out.results) >= 10
